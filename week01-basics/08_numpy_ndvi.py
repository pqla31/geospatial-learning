
import numpy as np
nir = np.array([
    [0.45, 0.42, 0.40, 0.38],
    [0.30, 0.28, 0.32, 0.29],
    [0.05, 0.06, 0.04, 0.07],
    [0.50, 0.48, 0.46, 0.44],
    [0.35, 0.33, 0.31, 0.30],
    [0.10, 0.12, 0.09, 0.11],
])
red = np.array([
    [0.08, 0.09, 0.10, 0.11],
    [0.28, 0.27, 0.30, 0.28],
    [0.12, 0.13, 0.10, 0.14],
    [0.06, 0.07, 0.08, 0.09],
    [0.20, 0.19, 0.18, 0.17],
    [0.11, 0.13, 0.10, 0.12],
])
ndvi = (nir - red) / (nir + red)
print(np.round(ndvi, 2))
print(f'均值 {ndvi.mean():.3f} | 最大 {ndvi.max():.3f} | 最小 {ndvi.min():.3f}')
print('像元数:', ndvi.size)
print(f'植被覆盖率 {(ndvi > 0.4).mean() * 100:.1f}%')